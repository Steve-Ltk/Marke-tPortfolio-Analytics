using Marke_tPortfolio_Analytics_web.Services;

var builder = WebApplication.CreateBuilder(args);

// ?? MVC ???????????????????????????????????????????????????????????????????????
builder.Services.AddControllersWithViews();

// ?? Session ???????????????????????????????????????????????????????????????????
// Nécessite un cache distribué en mémoire (dev) ou Redis (prod)
builder.Services.AddDistributedMemoryCache();
builder.Services.AddSession(options =>
{
    options.IdleTimeout = TimeSpan.FromMinutes(120); // 2h d'inactivité
    options.Cookie.HttpOnly = true;   // Inaccessible depuis JavaScript
    options.Cookie.IsEssential = true;   // Pas bloqué par RGPD cookie consent
    options.Cookie.SameSite = Microsoft.AspNetCore.Http.SameSiteMode.Lax;
    options.Cookie.SecurePolicy = Microsoft.AspNetCore.Http.CookieSecurePolicy.SameAsRequest;
});

// ?? HttpClient vers l'API backend ?????????????????????????????????????????????
// "ApiClient" est le nom nommé — utilisé dans ApiService via IHttpClientFactory
builder.Services.AddHttpClient("ApiClient", client =>
{
    var baseUrl = builder.Configuration["ApiSettings:BaseUrl"]
                  ?? throw new InvalidOperationException(
                      "ApiSettings:BaseUrl manquant dans appsettings.json");
    client.BaseAddress = new Uri(baseUrl);
    client.DefaultRequestHeaders.Add("Accept", "application/json");
    client.Timeout = TimeSpan.FromSeconds(30);
});

// ?? Services applicatifs ??????????????????????????????????????????????????????
builder.Services.AddScoped<IApiService, ApiService>();

// Accès au HttpContext dans les services (ex : ApiService lit la session)
builder.Services.AddHttpContextAccessor();

// ?? Logging (déjà inclus par défaut, on garde pour clarté) ???????????????????
builder.Logging.AddConsole();

// ????????????????????????????????????????????????????????????????????????????????
var app = builder.Build();
// ????????????????????????????????????????????????????????????????????????????????

// ?? Pipeline HTTP ?????????????????????????????????????????????????????????????
if (!app.Environment.IsDevelopment())
{
    app.UseExceptionHandler("/Home/Error");
    app.UseHsts();
}

app.UseHttpsRedirection();
app.UseStaticFiles();
app.UseRouting();

// UseSession DOIT être avant UseAuthorization
app.UseSession();
app.UseAuthorization();

// ?? Route par défaut : Auth/Login ?????????????????????????????????????????????
// Un utilisateur non connecté atterrit sur la page de connexion
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Auth}/{action=Login}/{id?}");

app.Run();


